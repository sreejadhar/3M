WITH claim_agg AS (
    SELECT
        c.ADJUSTER_ID,
        YEAR(TRY_TO_DATE(c.DATE_FILED::VARCHAR))  AS YR,
        MONTH(TRY_TO_DATE(c.DATE_FILED::VARCHAR)) AS MO,
        COUNT(*)                                  AS CLAIMS_HANDLED,
        AVG(DATEDIFF(DAY, TRY_TO_DATE(c.DATE_FILED::VARCHAR), TRY_TO_DATE(c.DATE_CLOSED::VARCHAR))) AS AVG_DTC,
        SUM(c.APPROVED_AMOUNT)                    AS TOTAL_APPROVED,
        SUM(CASE WHEN c.LITIGATION_FLAG::BOOLEAN THEN 1 ELSE 0 END) AS LIT_COUNT
    FROM PNC.CLAIM c

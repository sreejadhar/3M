assess_agg AS (
    SELECT
        ca.ADJUSTER_ID,
        YEAR(TRY_TO_DATE(ca.ASSESSMENT_DATE::VARCHAR))  AS YR,
        MONTH(TRY_TO_DATE(ca.ASSESSMENT_DATE::VARCHAR)) AS MO,
        COUNT(*)          AS ASSESSMENTS_DONE,

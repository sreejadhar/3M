-- 16. FACT_ADJUSTER_MONTHLY_SNAPSHOT
INSERT INTO PNC_DW.FACT_ADJUSTER_MONTHLY_SNAPSHOT
    (ADJUSTER_MONTHLY_SK, ADJUSTER_SK, SNAPSHOT_YEAR, SNAPSHOT_MONTH,

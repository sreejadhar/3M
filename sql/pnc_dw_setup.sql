    NVL(aa.TOTAL_HOURS,0),
    aa.AVG_REV,
    NVL(cl.LIT_COUNT,0)
FROM PNC_DW.DIM_ADJUSTER da
LEFT JOIN claim_agg  cl ON cl.ADJUSTER_ID = da.ADJUSTER_ID
LEFT JOIN assess_agg aa ON aa.ADJUSTER_ID = da.ADJUSTER_ID
                        AND aa.YR = cl.YR AND aa.MO = cl.MO
WHERE COALESCE(cl.YR, aa.YR) IS NOT NULL;


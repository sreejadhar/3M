-- 1. DIM_DATE (2015-01-01 to 2030-12-31)
INSERT INTO PNC_DW.DIM_DATE
    (DATE_SK, FULL_DATE, DAY_OF_MONTH, DAY_NAME, DAY_OF_WEEK, IS_WEEKEND,
     WEEK_OF_YEAR, MONTH, MONTH_NAME, QUARTER, YEAR,
     FISCAL_YEAR, FISCAL_QUARTER, IS_MONTH_END, IS_QUARTER_END, IS_YEAR_END)
WITH spine AS (
    SELECT DATEADD(DAY, SEQ4(), '2015-01-01'::DATE) AS d
    FROM TABLE(GENERATOR(ROWCOUNT => 5844))
)
SELECT
    ROW_NUMBER() OVER (ORDER BY d)                                  AS DATE_SK,
    d                                                               AS FULL_DATE,
    DAY(d)                                                          AS DAY_OF_MONTH,
    DAYNAME(d)                                                      AS DAY_NAME,
    CASE DAYOFWEEK(d) WHEN 0 THEN 7 ELSE DAYOFWEEK(d) END          AS DAY_OF_WEEK,
    DAYOFWEEK(d) IN (0, 6)                                          AS IS_WEEKEND,
    WEEKOFYEAR(d)                                                   AS WEEK_OF_YEAR,
    MONTH(d)                                                        AS MONTH,
    MONTHNAME(d)                                                    AS MONTH_NAME,
    QUARTER(d)                                                      AS QUARTER,
    YEAR(d)                                                         AS YEAR,
    YEAR(d)                                                         AS FISCAL_YEAR,
    QUARTER(d)                                                      AS FISCAL_QUARTER,
    d = LAST_DAY(d)                                                 AS IS_MONTH_END,
    d = LAST_DAY(d) AND MONTH(d) IN (3,6,9,12)                     AS IS_QUARTER_END,
    MONTH(d) = 12 AND d = LAST_DAY(d)                               AS IS_YEAR_END
FROM spine;


CREATE OR REPLACE VIEW PNC_DW.V_CLAIM_PERFORMANCE AS
SELECT
    d.YEAR,
    d.QUARTER,
    d.MONTH_NAME,
    dph.STATE,
    fc.CLAIM_STATUS,
    fc.SEVERITY,
    dct.CLAIM_TYPE,
    COUNT(*)                                                    AS CLAIM_COUNT,
    SUM(fc.CLAIMED_AMOUNT)                                      AS TOTAL_CLAIMED,
    SUM(fc.APPROVED_AMOUNT)                                     AS TOTAL_APPROVED,
    SUM(fc.TOTAL_PAID_AMOUNT)                                   AS TOTAL_PAID,
    AVG(fc.DAYS_TO_CLOSE)                                       AS AVG_DAYS_TO_CLOSE,
    SUM(CASE WHEN fc.LITIGATION_FLAG  THEN 1 ELSE 0 END)        AS LITIGATION_COUNT,
    SUM(CASE WHEN fc.HAS_FRAUD_INDICATOR THEN 1 ELSE 0 END)     AS FRAUD_FLAG_COUNT,
    AVG(fc.CLAIM_RECOVERY_PCT)                                  AS AVG_RECOVERY_PCT
FROM PNC_DW.FACT_CLAIMS fc
JOIN PNC_DW.DIM_DATE         d   ON d.DATE_SK           = fc.DATE_FILED_SK
JOIN PNC_DW.DIM_POLICYHOLDER dph ON dph.POLICYHOLDER_SK = fc.POLICYHOLDER_SK
LEFT JOIN PNC_DW.DIM_CLAIM_TYPE dct ON dct.CLAIM_TYPE_SK = fc.CLAIM_TYPE_SK
GROUP BY 1,2,3,4,5,6,7;


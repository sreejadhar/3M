        AVG(ca.REVISION_COUNT) AS AVG_REV
    FROM PNC.CLAIM_ASSESSMENT ca
    WHERE TRY_TO_DATE(ca.ASSESSMENT_DATE::VARCHAR) IS NOT NULL
    GROUP BY 1,2,3
)
SELECT
    PNC_DW.SEQ_FACT_ADJ_MON_SK.NEXTVAL,
    da.ADJUSTER_SK,
    COALESCE(cl.YR, aa.YR)             AS SNAPSHOT_YEAR,

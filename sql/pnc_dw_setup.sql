     CLAIMED_AMOUNT, APPROVED_AMOUNT, DEDUCTIBLE_APPLIED,
     NET_APPROVED_AMOUNT, TOTAL_PAID_AMOUNT, CLAIM_RECOVERY_PCT, DAYS_TO_CLOSE)
WITH paid AS (
    SELECT CLAIM_ID, SUM(PAYMENT_AMOUNT) AS TOTAL_PAID FROM PNC.CLAIM_PAYMENT GROUP BY CLAIM_ID
),
fraud AS (
    SELECT CLAIM_ID, FRAUD_SCORE, FRAUD_RISK_LEVEL, PRIMARY_INDICATOR,
           ROW_NUMBER() OVER (PARTITION BY CLAIM_ID ORDER BY DETECTION_DATE DESC) AS rn
    FROM PNC.FRAUD_INDICATOR
)
SELECT
    PNC_DW.SEQ_FACT_CLAIMS_SK.NEXTVAL,
    c.CLAIM_ID,
    dp.POLICY_SK,
    dp.POLICYHOLDER_SK,
    da.ADJUSTER_SK,
    dp.AGENT_SK,
    dct.CLAIM_TYPE_SK,
    dfr.FRAUD_RISK_LEVEL_SK,
    ddf.DATE_SK,
    ddc.DATE_SK,
    c.CLAIM_STATUS,
    c.SEVERITY,
    c.REPORTING_METHOD,
    TRY_CAST(c.LITIGATION_FLAG  AS BOOLEAN),
    TRY_CAST(c.SUBROGATION_FLAG AS BOOLEAN),
    (f.CLAIM_ID IS NOT NULL),
    f.FRAUD_SCORE,
    c.CLAIMED_AMOUNT,
    c.APPROVED_AMOUNT,
    c.DEDUCTIBLE_APPLIED,
    NVL(c.APPROVED_AMOUNT,0) - NVL(c.DEDUCTIBLE_APPLIED,0),
    NVL(p2.TOTAL_PAID,0),
    IFF(c.CLAIMED_AMOUNT > 0, c.APPROVED_AMOUNT / c.CLAIMED_AMOUNT, NULL),
    DATEDIFF(DAY, TRY_TO_DATE(c.DATE_FILED::VARCHAR), TRY_TO_DATE(c.DATE_CLOSED::VARCHAR))
FROM PNC.CLAIM c
LEFT JOIN PNC_DW.DIM_POLICY           dp  ON dp.POLICY_ID    = c.POLICY_ID
LEFT JOIN PNC_DW.DIM_ADJUSTER         da  ON da.ADJUSTER_ID  = c.ADJUSTER_ID
LEFT JOIN PNC_DW.DIM_CLAIM_TYPE       dct ON dct.CLAIM_TYPE  = TRIM(c.CLAIM_TYPE)
                                         AND dct.CLAIMANT_TYPE = TRIM(c.CLAIMANT_TYPE)
LEFT JOIN fraud                        f   ON f.CLAIM_ID      = c.CLAIM_ID AND f.rn = 1
LEFT JOIN PNC_DW.DIM_FRAUD_RISK_LEVEL dfr ON dfr.FRAUD_RISK_LEVEL = TRIM(f.FRAUD_RISK_LEVEL)
                                         AND dfr.PRIMARY_INDICATOR  = TRIM(f.PRIMARY_INDICATOR)
LEFT JOIN PNC_DW.DIM_DATE             ddf ON ddf.FULL_DATE    = TRY_TO_DATE(c.DATE_FILED::VARCHAR)
LEFT JOIN PNC_DW.DIM_DATE             ddc ON ddc.FULL_DATE    = TRY_TO_DATE(c.DATE_CLOSED::VARCHAR)
LEFT JOIN paid                         p2  ON p2.CLAIM_ID     = c.CLAIM_ID;

